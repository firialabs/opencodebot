// Converts CircuitPython's terminal font (Terminus 6x12, SIL Open Font
// License 1.1) to the table src/sim/world/fonts/terminus6x12.js:
//   node sim/tools/build-font.mjs path/to/ter-u12n.bdf
// The BDF is tools/fonts/ter-u12n.bdf in github.com/adafruit/circuitpython.
import fs from 'node:fs'
import path from 'node:path'

const bdf = fs.readFileSync(process.argv[2], 'utf8')
const glyphs = {}
for (const block of bdf.split('STARTCHAR').slice(1)) {
  const enc = Number(/ENCODING (\d+)/.exec(block)[1])
  // ASCII, Latin-1 and the block and arrow glyphs programs draw with
  if (!(enc >= 32 && enc <= 255) && !(enc >= 0x2190 && enc <= 0x2193) && !(enc >= 0x2580 && enc <= 0x259f)) continue
  const [, w, h, , yoff] = /BBX (\d+) (\d+) (-?\d+) (-?\d+)/.exec(block).map(Number)
  const bitmap = /BITMAP\n([\s\S]*?)ENDCHAR/.exec(block)[1].trim().split('\n').filter(Boolean)
  // Place in the 12-row cell: the font's descent is 2, so row 0 is 10 above the baseline.
  const rows = new Array(12).fill(0)
  const top = 10 - (h + yoff)
  bitmap.forEach((hex, i) => { rows[top + i] = parseInt(hex, 16) >> (8 - w) })
  glyphs[enc] = rows
}
const out = `// Terminus 6x12, CircuitPython's terminal font. Copyright (C) 2018 Dimitar
// Toshkov Zhekov, licensed under the SIL Open Font License, Version 1.1.
// Generated by sim/tools/build-font.mjs; each glyph is 12 rows, 6 bits, MSB left.
const G = ${JSON.stringify(glyphs)}
const UNKNOWN = G[63]
export const TERMINUS_6X12 = { w: 6, h: 12, glyph: (ch) => G[ch.codePointAt(0)] ?? UNKNOWN }
`
fs.writeFileSync(path.resolve(import.meta.dirname, '../../src/sim/world/fonts/terminus6x12.js'), out)
console.log(Object.keys(glyphs).length, 'glyphs')
