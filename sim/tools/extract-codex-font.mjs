// Extracts CodeX's built-in 6x8 font from its firmware image into
// src/sim/world/fonts/codex6x8.js:
//   node sim/tools/extract-codex-font.mjs path/to/codex_05-21-2024_gGA-050224.bin
// The table is 96 glyphs (0x20-0x7F), 6 bytes each, one byte per column, bit 0
// the top row, at file offset 0x3B254 in that image.
import fs from 'node:fs'
import path from 'node:path'

const OFFSET = 0x3b254
const fw = fs.readFileSync(process.argv[2])
const glyphs = []
for (let g = 0; g < 96; g++) {
  const cols = fw.subarray(OFFSET + g * 6, OFFSET + g * 6 + 6)
  const rows = []
  for (let r = 0; r < 8; r++) {
    let bits = 0
    for (let c = 0; c < 6; c++) bits = (bits << 1) | ((cols[c] >> r) & 1)
    rows.push(bits)
  }
  glyphs.push(rows)
}
const out = `// CodeX's built-in font: 6x8 cells, ASCII 0x20-0x7F, from its firmware, which
// carries Adafruit GFX's classic 5x7 font (glcdfont.c) with "~" redrawn.
// Copyright (c) 2012 Adafruit Industries, BSD licence (THIRD_PARTY_NOTICES.md).
// Generated by sim/tools/extract-codex-font.mjs; each glyph is 8 rows, 6 bits, MSB left.
const G = ${JSON.stringify(glyphs)}
export const CODEX_6X8 = {
  w: 6,
  h: 8,
  glyph(ch) {
    const c = ch.codePointAt(0)
    return c >= 0x20 && c <= 0x7f ? G[c - 0x20] : G[0x3f - 0x20]
  },
}
`
fs.writeFileSync(path.resolve(import.meta.dirname, '../../src/sim/world/fonts/codex6x8.js'), out)
console.log('wrote', glyphs.length, 'glyphs')
